import EmbeddedPostgres from 'embedded-postgres';
import {existsSync,mkdirSync} from 'node:fs';
const directory=new URL('../work/postgres/',import.meta.url).pathname;
mkdirSync(directory,{recursive:true});
const pg=new EmbeddedPostgres({databaseDir:directory,user:'bloom',password:'bloom',port:5432,persistent:true,postgresFlags:['-c','listen_addresses=127.0.0.1','-c','unix_socket_directories=/tmp'],onLog:()=>{},onError:console.error});
if(!existsSync(directory+'PG_VERSION'))await pg.initialise();
await pg.start();
const client=pg.getPgClient();await client.connect();const result=await client.query("SELECT 1 FROM pg_database WHERE datname='bloom'");await client.end();if(!result.rowCount)await pg.createDatabase('bloom');
console.log('Local PostgreSQL ready on 127.0.0.1:5432. Development credentials only.');
const stop=async()=>{await pg.stop();process.exit(0);};process.on('SIGINT',stop);process.on('SIGTERM',stop);
setInterval(()=>{},60000);
